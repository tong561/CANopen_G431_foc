float Encoder_GetCorrectedRaw(uint16_t raw)
{
    uint16_t index;
    uint16_t next;
    uint16_t sub;

    float frac;
    float err;
    float corrected;

    index = raw >> 4;          // 0 ~ 1023
    sub   = raw & 0x000F;      // 0 ~ 15

    next = index + 1;
    if(next >= MT6816_LUT_SIZE)
        next = 0;

    frac = (float)sub / 16.0f;

    err =
        MT6816_ErrorLUT[index] +
        frac *
        (MT6816_ErrorLUT[next] -
         MT6816_ErrorLUT[index]);

    /* 保持第二版方向 */
    corrected = (float)raw - err;

    if(corrected >= 16384.0f)
        corrected -= 16384.0f;

    if(corrected < 0.0f)
        corrected += 16384.0f;

    return corrected;
}


#define TWO_PI 6.28318530717958647692f

float Encoder_RawToRad(float raw)
{
    return raw *
           TWO_PI /
           (float)MT6816_CPR;
}
